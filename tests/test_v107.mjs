import assert from 'node:assert/strict';
import {visibleRegionMeshes,tileInHorizontalView} from '../js/region_visibility.js';
import {buildRegionTerrain} from '../js/region3d_geometry.js';
import {parseGeoPack} from '../js/geopack.js';
import {BUILTIN_GEOPACK} from '../js/bundled_geopack.js';
import {mercatorProject} from '../js/region_tiles.js';
const camera={x:0,z:0};
const near={originX:-192,originZ:0,tileSpan:384,triangles:15};
const front={originX:-192,originZ:2100,tileSpan:384,triangles:900};
const back={originX:-192,originZ:-2100,tileSpan:384,triangles:500};
const side={originX:3200,originZ:0,tileSpan:384,triangles:250};
assert(tileInHorizontalView(near,camera,0));
assert(tileInHorizontalView(front,camera,0),'tile straight ahead visible');
assert(!tileInHorizontalView(back,camera,0),'behind camera culled');
assert(!tileInHorizontalView(side,camera,0),'outside field of view culled');
const selection=visibleRegionMeshes([near,front,back,side],camera,0,{});
assert.equal(selection.visible.length,2);
assert.equal(selection.culled,2);
assert.equal(selection.trianglesCulled,750);
const pack=parseGeoPack(BUILTIN_GEOPACK),p=mercatorProject(36.506491,45.30844);
const tile=buildRegionTerrain(pack,{tx:Math.floor(p.x/384),ty:Math.floor(p.y/384),step:24});
const n=tile.lod;
assert.equal(tile.skirtTriangles,8*n,'all four terrain edges have skirts');
assert.equal(tile.triangles,2*n*n+8*n,'skirt triangles are appended but no measured surface invented');
assert.equal(tile.array.length,7*tile.count);
assert.equal(tile.tileSpan,384);
assert(tile.array.every(Number.isFinite));
console.log(`PASS 10.7: frustum culling ${selection.culled} tiles / ${selection.trianglesCulled} triangles, terrain skirts ${tile.skirtTriangles}, complete local Float32 meshes`);
