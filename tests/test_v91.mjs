import assert from 'node:assert/strict';
import {World3D} from '../js/world3d.js';
import {BRIDGES,makeBridge} from '../js/data.js';
const noop=()=>{};
const ctx={fillRect:noop,beginPath:noop,stroke:noop,fill:noop,moveTo:noop,lineTo:noop,clearRect:noop,arc:noop,createPattern:()=>({}),createLinearGradient:()=>({addColorStop:noop}),setTransform:noop};
globalThis.document={createElement:()=>({getContext:()=>ctx})};
globalThis.window={addEventListener:noop};globalThis.devicePixelRatio=1;
globalThis.performance={now:()=>1000};
const canvas={clientWidth:1024,clientHeight:640,width:0,height:0,style:{display:'block'},getContext:kind=>kind==='2d'?ctx:null,addEventListener:noop};
const world=new World3D(canvas);world.renderSoftware=noop;
const cfg=BRIDGES.find(v=>v.id==='kerch');
const payload={id:'kerch',track:'bridge',soil:cfg.soil,span:cfg.span,model:makeBridge(cfg)};
world.start(payload);
const bounds=world.kerchBounds();
const controls=world.getRouteControls();
assert(world.routeLengthKm()>18.0&&world.routeLengthKm()<22.0,'illustrative length should be approximately 19 km');
const offshore=world.mapHeight(14,68);
assert.equal(controls.length,13);
const index=8,x=controls[index].x;
const initial=world.kerchCenter(x),adjacentX=x+(controls[index+1].x-x)*0.3;
const adjacentBefore=world.kerchCenter(adjacentX);
const initialBridgePoint=world.kerchSample(x,bounds.railSide);
const staticBuilds=world.staticBuilds;
assert(world.setRouteOffset(index,5.5));
assert.equal(world.routeOffsets[index],5.5);
assert(Math.abs(world.kerchCenter(x)-initial-5.5)<1e-7);
assert(world.kerchCenter(adjacentX)>adjacentBefore+0.2,'smooth interpolation not applied to neighboring route');
assert(Math.abs(world.kerchSample(x,bounds.railSide)[2]-initialBridgePoint[2]-5.5)<1e-7,'3D railway alignment not synchronized');
assert(world.sceneDirty,'route edit must invalidate static bridge');
assert(Math.abs(world.mapHeight(14,68)-offshore)<1e-8,'route edit must not move the fixed coastline far from the route');
for(let i=0;i<=60;i++){
 const t=bounds.x0+(bounds.x1-bounds.x0)*i/60;
 assert(Number.isFinite(world.kerchCenter(t)));
}
world.render(payload,true);
assert.equal(world.staticBuilds,staticBuilds+1);
assert(world.mesh.a.every(Number.isFinite));
assert.equal(world.setRouteOffset(0,7),true,'Kerch endpoint now editable');
assert.equal(world.setRouteOffset(12,7),true,'Taman endpoint now editable');
const saved=[...world.routeOffsets];
world.resetRoute();assert.equal(world.routeOffsets[index],0);
assert(world.setRouteOffsets(saved));assert.equal(world.routeOffsets[index],5.5);
assert.equal(world.setRouteOffsets(new Array(13).fill(Infinity)),false);
console.log('PASS 9.1 + 9.4.1: 2D/3D route interpolation, editable ends, undo-compatible snapshots, re-render');
