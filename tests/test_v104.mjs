import assert from 'node:assert/strict';
import {parseGeoPack} from '../js/geopack.js';
import {BUILTIN_GEOPACK} from '../js/bundled_geopack.js';
import {BUNDLED_REGION_DEMO} from '../js/bundled_region_demo.js';
import {RegionTileStore,mercatorProject,mercatorUnproject} from '../js/region_tiles.js';
import {floatingOrigin,gpuLocalPosition,chooseTerrainLOD,visibleTerrainPlan,sampleRegionGround,buildRegionTerrain,buildRegionCityTile,REGION_GROUND_SCALE} from '../js/region3d_geometry.js';
import {Region3D} from '../js/region3d.js';
import {probeWebGPU,REGION_WGSL_SMOKE} from '../js/webgpu_probe.js';
const p=parseGeoPack(BUILTIN_GEOPACK);
assert(p.coast&&p.dem&&p.gridSize===512,'actual user 512² GeoPack is bundled');
const center=mercatorProject(36.506491,45.30844);
const geo=mercatorUnproject(center.x,center.y);
assert(Math.abs(geo.lat-45.30844)<1e-8&&Math.abs(geo.lon-36.506491)<1e-8);
const ground=sampleRegionGround(p,center.x,center.y);
assert.equal(ground.measured,true,'source DSM must exist at anchor');
const distant=mercatorProject(35.4,44.8);
assert.equal(sampleRegionGround(p,distant.x,distant.y).measured,false,'must not invent DEM outside supplied coverage');
const floating=floatingOrigin(center.x,-center.y);
const [gx,gz]=gpuLocalPosition(center.x,center.y,floating);
assert(Math.abs(gx)<768&&Math.abs(gz)<768,'local GPU coordinates must remain small');
for(let delta of [0,1,1234.567,250000]){
 const o=floatingOrigin(center.x+delta,-center.y-321.1357);
 const [a,b]=gpuLocalPosition(center.x+delta,center.y+321.1357,o);
 assert(Math.abs(a)<=768&&Math.abs(b)<=768);
 assert(Math.abs((o.x+a/REGION_GROUND_SCALE)-(center.x+delta))<1e-4,'rebased float coordinate should maintain <0.1mm error');
}
assert(chooseTerrainLOD(40,'ultra')<chooseTerrainLOD(2000,'ultra'));
const plan=visibleTerrainPlan(center.x,-center.y,{quality:'high'});
assert(plan.length>20&&plan.length<110);
assert(plan[0].dist<=plan[1].dist,'terrain should build nearby first');
assert(plan.every(x=>Math.abs(x.tx)<1e7&&x.step>0));
let terrain=buildRegionTerrain(p,plan[0]);
assert(terrain.count>100&&terrain.triangles===terrain.count/3);
assert(terrain.validFraction>0&&terrain.validFraction<=1);
assert(terrain.array.length===terrain.count*7);
assert([...terrain.array].every(Number.isFinite));
let unknown=buildRegionTerrain(p,{tx:Math.floor(distant.x/384),ty:Math.floor(distant.y/384),step:48});
assert(unknown.validFraction===0,'unknown geography must stay explicitly unmeasured');
assert(BUNDLED_REGION_DEMO.index.metadata.sources[0].includes('SYNTHETIC'));
const store=new RegionTileStore({limit:8,parallel:2});store.setManifest(BUNDLED_REGION_DEMO.index,{inline:new Map(Object.entries(BUNDLED_REGION_DEMO.tiles)),mode:'offline demo'});
const [key,meta]=Object.entries(BUNDLED_REGION_DEMO.index.tiles).find(([k,v])=>v.features>30)||Object.entries(BUNDLED_REGION_DEMO.index.tiles)[0];
const fc=BUNDLED_REGION_DEMO.tiles[meta.path],tx=Number(key.split(':')[0]),ty=Number(key.split(':')[1]);
const city=buildRegionCityTile(p,fc,{tx,ty,tileSizeMeters:store.index.size});
assert(city.count>=0&&city.sourceFeatures===fc.features.length);
assert(city.buildings+city.roads+city.rails>0,'bundled GIS demo must make renderable geometry');
assert(city.array.length===city.count*7);
assert.equal((await probeWebGPU(null)).supported,false);
assert(REGION_WGSL_SMOKE.includes('@vertex')&&REGION_WGSL_SMOKE.includes('@fragment'));
// No browser/GPU necessary to test bounded tile streaming and rebase invariants.
const noop=()=>{},ctx={fillRect:noop,fillText:noop,setTransform:noop};
globalThis.window={addEventListener:noop,devicePixelRatio:1};globalThis.document={getElementById:()=>null};
const canvas={clientWidth:700,clientHeight:450,width:0,height:0,addEventListener:noop,getContext:k=>k==='2d'?ctx:null,focus:noop};
const region=new Region3D({overlay:{hidden:true,style:{}},canvas,status:{textContent:''},geoPack:p,store});
region._stream();const builtBefore=region.stats.terrainBuilt;assert(builtBefore>0);
region.cam.x+=801;region._step(0);const after=region.stats.rebases;assert(after>=1);
region._stream();assert(region.stats.terrainBuilt>builtBefore,'moving requires only new terrain tiles');
assert(region.terrainCache.size<=100&&region.cityCache.size<=40,'bounded GPU/CPU tile caches');
assert(Math.abs(REGION_GROUND_SCALE-.703)<.01,'ground-corrected local metres near Kerch');
assert.equal(region.stats.uploads,0,'software test must not fabricate GPU uploads');
console.log(`PASS 10.4: real DEM / terrain ${terrain.count} vertices / unknown gap / float origin / building mesh / bounded LRU / WebGPU probe / offline HTML demo`);
