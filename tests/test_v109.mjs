import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {RegionAssetStream,regionAssetRaycast} from '../js/region_assets.js';
import {parseGeoPack} from '../js/geopack.js';import {BUILTIN_GEOPACK} from '../js/bundled_geopack.js';
import {mercatorProject} from '../js/region_tiles.js';
const pack=parseGeoPack(BUILTIN_GEOPACK),s=new RegionAssetStream(pack,{seedDemo:true});
const pos=s.instances[0],cam=mercatorProject(pos.lon,pos.lat);
const hit=regionAssetRaycast(pack,{x:cam.x,y:180,z:-cam.y},[0,-1,0],{maxDistance:500});
assert(hit,'Downward ray hits measured land');
assert(Math.hypot(hit.lon-pos.lon,hit.lat-pos.lat)<1e-7,'Hit geodetic position stable');
assert.equal(regionAssetRaycast(pack,{x:cam.x,y:180,z:-cam.y},[0,1,0]),null,'Sky is not hit');
const f=readFileSync(new URL('../assets/models/lighthouse_high.glb',import.meta.url));
s.registerGLB('user_light',new Uint8Array(f),{label:'Custom light'});
s.add({assetId:'user_light',lon:pos.lon,lat:pos.lat,source:'manual WGS84 asset placement'});
let scene=s.exportPlacements();assert.equal(scene.models.length,1);assert.equal(scene.models[0].encoding,'base64/GLB');
const fresh=new RegionAssetStream(pack,{seedDemo:false});assert.equal(fresh.importPlacements(scene),s.instances.length);
assert.equal(fresh.catalog.get('user_light').variants.high.triangles,s.catalog.get('user_light').variants.high.triangles);
const migrated=fresh.exportPlacements();assert.equal(migrated.models.length,1);
const before=fresh.instances.length;fresh.add({assetId:'warehouse',lon:pos.lon,lat:pos.lat});assert.equal(fresh.instances.length,before+1);
assert(fresh.remove(fresh.instances.at(-1).id));assert.equal(fresh.instances.length,before);
assert.throws(()=>fresh.importPlacements({...scene,type:'nope'}),/TrussLabAssetScene/);
assert.throws(()=>fresh.importPlacements({...scene,models:[{id:'infected',encoding:'remote-code',data:'https://untrusted'}]}),/GLB/);
console.log('PASS 10.9: terrain raycast, WGS84 placement, local GLB binary embedded into JSON, export/import, reject unsafe scene');
