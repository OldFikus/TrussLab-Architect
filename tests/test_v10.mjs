import assert from 'node:assert/strict';
import {World3D} from '../js/world3d.js';
import {BUILTIN_GEOPACK} from '../js/bundled_geopack.js';
import {BRIDGES,makeBridge} from '../js/data.js';
const noop=()=>{};
const ctx={fillRect:noop,beginPath:noop,stroke:noop,fill:noop,moveTo:noop,lineTo:noop,clearRect:noop,arc:noop,createPattern:()=>({}),createLinearGradient:()=>({addColorStop:noop}),setTransform:noop};
globalThis.document={createElement:()=>({getContext:()=>ctx})};globalThis.window={addEventListener:noop};globalThis.devicePixelRatio=1;globalThis.performance={now:()=>1500};
const canvas={clientWidth:1100,clientHeight:700,width:0,height:0,style:{display:'block'},getContext:k=>k==='2d'?ctx:null,addEventListener:noop};
const world=new World3D(canvas);world.renderSoftware=noop;
const sc=BRIDGES.find(b=>b.id==='kerch');const payload={id:'kerch',track:'bridge',soil:sc.soil,span:sc.span,model:makeBridge(sc)};
world.start(payload);
assert.equal(BUILTIN_GEOPACK.type,'TrussLabGeoPack');
assert.equal(BUILTIN_GEOPACK.gridSize,512);
assert.equal(BUILTIN_GEOPACK.metadata.sources[1].details.landFraction,.3599);
const info=world.loadGeoPack(BUILTIN_GEOPACK);
assert(info.osm&&info.dem);
assert(world.setRouteExtents({x0:-160.5,x1:156}));
assert.equal(world.coastMode,'osm');assert.equal(world.demEnabled,true);
const qa=world.routeCoastDiagnostics({detail:false});
for(const name of ['road','rail']){
 const r=qa.tracks[name];assert(r.startLand&&r.endLand,`${name} endpoints must be on land`);
 assert(r.shoreCrossings>=2,`${name} should cross both main shores`);
}
assert(world.routeLengthKm()>24 && world.routeLengthKm()<27,'actual mapped scheme 25.x km, not claimed 19 km');
for(const point of [[-195,-4],[0,0],[186,-10]])assert(Number.isFinite(world.mapHeight(...point)));
const h=world.sampleDEMMetres(-180,-5);assert(h!==null&&h>0,'actual user DEM expected');
world.setSunHour(22);assert.equal(world.daylight,'night');
assert(world.nearestLampPositions().length===12,'ultra night should light road with 12 local sources');
world.setSunHour(13);assert.equal(world.daylight,'day');
assert.equal(world.nearestLampPositions().length,0,'lamps are turned off during day');
world.setSunHour(19);assert.equal(world.daylight,'sunset');
world.setSunHour(22);world.lampsEnabled=false;assert.equal(world.nearestLampPositions().length,0);
world.shadowsEnabled=false;world.render(payload,true);
const staticBuilds=world.staticBuilds;world.tick(1560);world.tick(1700);
assert.equal(world.staticBuilds,staticBuilds,'traffic animation must not rebuild map/bridge');
world.setTrafficEnabled(false);assert.equal(world.trafficCount,0);
assert.equal(world.geoPackSource,BUILTIN_GEOPACK,'OSM/DEM payload preserved unchanged');
console.log('PASS 10.0: actual 512² OSM+GLO-30 GeoPack, 35.99% land, coast-anchored endpoints, sun cycle, 12 nearest lamps, GPU shadow controls, traffic isolation');
