import assert from 'node:assert/strict';
import {BUILTIN_GEOPACK} from '../js/bundled_geopack.js';
import {BUNDLED_REGION_DEMO} from '../js/bundled_region_demo.js';
import {parseGeoPack} from '../js/geopack.js';
import {buildRegionCityTile,regionCityDetail} from '../js/region3d_geometry.js';
import {REGION_QUALITY_PROFILES,RegionQualityGovernor,meshCpuBytes,evictMeshBytes} from '../js/region_quality.js';
import {REGION_WGSL_RENDER} from '../js/webgpu_renderer.js';
const pack=parseGeoPack(BUILTIN_GEOPACK);
const {index,tiles}=BUNDLED_REGION_DEMO;
let collected=[];
for(const [key,entry] of Object.entries(index.tiles)){
 const [tx,ty]=key.split(':').map(Number);
 const fc=tiles[entry.path];
 const result=buildRegionCityTile(pack,fc,{tx,ty,tileSizeMeters:index.tileSizeMeters||index.tileSize||index.size||2048,detail:'base'});
 if(result.buildings>0){collected.push({key,entry,fc,tx,ty});}
}
assert(collected.length>0,'bundled demo must have a building feature');
const candidate=collected[0];
const opts={tx:candidate.tx,ty:candidate.ty,tileSizeMeters:index.tileSizeMeters||2048};
const base=buildRegionCityTile(pack,candidate.fc,{...opts,detail:'base'});
const roof=buildRegionCityTile(pack,candidate.fc,{...opts,detail:'roof'});
const facade=buildRegionCityTile(pack,candidate.fc,{...opts,detail:'facade'});
assert(base.buildings>0);assert.equal(base.windowQuads,0);assert.equal(base.parapets,0);
assert(roof.parapets>0,'detailed roof parapets');assert(roof.count>base.count);
assert(facade.windowQuads>0,'facade window geometry must be present');assert(facade.count>roof.count);
assert(facade.count<base.count*20+20000,'LOD details need a finite budget');
for(const m of [base,roof,facade])assert.equal(m.count*7,m.array.length);
assert.equal(regionCityDetail(40,'ultra'),'facade');
assert.equal(regionCityDetail(4000,'ultra'),'base');
assert.equal(regionCityDetail(1000,'high'),'roof');
assert.equal(regionCityDetail(300,'low'),'base');
const g=new RegionQualityGovernor({level:'high',cooldown:4500,target:50});
for(const t of [1000,2000,3000,5000,6000])g.observe(17,t,true);
assert.equal(g.level,'medium','low FPS must reduce quality');
for(const t of [7000,8000,9000,10500,11000])g.observe(13,t,true);
assert.equal(g.level,'low','repeated low FPS should reduce to minimum');
const old=g.level;g.observe(120,20000,false);assert.equal(g.level,old,'manual selection disables governor');
assert(REGION_QUALITY_PROFILES.high.cpuBudgetMB>REGION_QUALITY_PROFILES.low.cpuBudgetMB);
const m1=new Map([['a',{array:new Float32Array(100)}],['b',{array:new Float32Array(100)}]]),m2=new Map([['c',{array:new Float32Array(100)}]]);
assert.equal(meshCpuBytes(m1,m2),1200);
const released=[];const result=evictMeshBytes([m1,m2],{limitBytes:500,keep:new Set(['b']),dispose:e=>released.push(e)});
assert(result.bytes<=500&&released.length===2&&m1.has('b'));
assert(REGION_WGSL_RENDER.includes('scene.fog.w')&&REGION_WGSL_RENDER.includes('id < 10.5'));
console.log(`PASS 10.6: ${base.triangles}/${roof.triangles}/${facade.triangles} triangles LOD, ${facade.windowQuads} facade windows, budget eviction, FPS governor, WebGPU materials`);
